/**
 *Representa los tipos de eventos climaticos que se pueden
 * registrar en el sistema
 * @author Maricela
 */
public enum TipoEventoClimatico {
    /**Lluvia abundante en un corto tiémpo*/
    LLUVIA_COPIOSA,
    /** Aumento del nivel del rio por encima de lo normal*/
    CRECIDA_RIO,
    /** Tormenta con vientos fuertes, rayos o granizo*/
    TORMENTA_SEVERA
}
